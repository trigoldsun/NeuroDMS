const fs=require('fs')
function patch(p,pairs){
  let raw=fs.readFileSync(p,'utf8'); const crlf=raw.includes('\r\n')
  let s=crlf?raw.replace(/\r\n/g,'\n'):raw
  for(const [a,b] of pairs){ if(!s.includes(a)) throw new Error('miss in '+p+' :: '+a.slice(0,50)); s=s.replace(a,b) }
  if(crlf) s=s.replace(/\n/g,'\r\n'); fs.writeFileSync(p,s); console.log('patched',p)
}

